const DICT: Record<Lang, Record<Key, string>> = { tr, en };

export type Vars = Record<string, string | number>;
export type TFn = (key: Key, vars?: Vars) => string;

export function translate(lang: Lang, key: Key, vars?: Vars): string {
  let s: string = DICT[lang][key] ?? DICT.tr[key] ?? key;
  if (vars) for (const k of Object.keys(vars)) s = s.split(`{${k}}`).join(String(vars[k]));
  return s;
}

export function errorText(lang: Lang, code: string): string {
  const key = `err.${code}` as Key;
  return key in DICT.tr ? translate(lang, key) : translate(lang, 'err.unknown', { code });
}
